import fs from "node:fs";
import path from "node:path";

const DEPLOY_DIR = path.join(__dirname, "..", "deploy");

// The rebuilt site replaces the legacy PHP site in place on the same domain
// it's always run on — no domain migration.
const PRIMARY_DOMAIN = "albanyairport.taxi"; // apex, non-www

type Redirect = { from: string; to: string };

function parseLegacyUrl(from: string): { script: string; query: string } {
  const [script, query = ""] = from.replace(/^\//, "").split("?");
  return { script, query };
}

function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function main() {
  const redirects = JSON.parse(
    fs.readFileSync(path.join(DEPLOY_DIR, "redirects.json"), "utf8")
  ) as Redirect[];

  // deploy/.htaccess goes in the primary domain's docroot alongside the
  // static export, replacing the legacy PHP site entirely. Handles canonical
  // host enforcement, every legacy ?id=/&cid=/&coid= URL redirect (same
  // domain, so these are relative path rewrites), and the apple-icon MIME
  // fix (app/apple-icon.tsx exports a real extensionless file — confirmed
  // by fetching it locally: without this, servers default to
  // application/octet-stream instead of image/png, and iOS won't use it).
  const lines: string[] = [];
  lines.push("# Generated by scripts/generate-htaccess.ts — do not hand-edit.");
  lines.push("# Regenerate via: npm run parse-dump && npm run generate-redirects && npm run generate-htaccess");
  lines.push("");
  lines.push("RewriteEngine On");
  lines.push("");
  lines.push("# --- Canonical host: force apex, non-www, https ---");
  lines.push(`RewriteCond %{HTTP_HOST} ^www\\.${PRIMARY_DOMAIN.replace(/\./g, "\\.")}$ [NC]`);
  lines.push(`RewriteRule ^(.*)$ https://${PRIMARY_DOMAIN}/$1 [R=301,L]`);
  lines.push("RewriteCond %{HTTPS} off");
  lines.push(`RewriteRule ^(.*)$ https://${PRIMARY_DOMAIN}/$1 [R=301,L]`);
  lines.push("");
  lines.push("# --- Disable directory listings (defense in depth; every route folder ---");
  lines.push("# --- now has a real index.html via next.config.ts's trailingSlash) ---");
  lines.push("Options -Indexes");
  lines.push("");
  lines.push("# --- Legacy URL redirects (generated from the old PHP site's sitemap) ---");

  for (const redirect of redirects) {
    // Skip identity redirects (e.g. "/" -> "/") — the legacy sitemap parser
    // can emit these for URLs that already resolve correctly, but turning
    // one into an R=301 rule makes Apache redirect the path to itself,
    // looping forever.
    if (redirect.from === redirect.to) continue;
    const { script, query } = parseLegacyUrl(redirect.from);
    if (!query) {
      lines.push(`RewriteRule ^${escapeRegex(script)}$ ${redirect.to}? [R=301,L]`);
      continue;
    }
    const escapedQuery = escapeRegex(query);
    lines.push(`RewriteCond %{QUERY_STRING} ^${escapedQuery}$`);
    lines.push(`RewriteRule ^${escapeRegex(script)}$ ${redirect.to}? [R=301,L]`);
  }

  lines.push("");
  lines.push("# --- apple-icon exports as an extensionless file; force its real MIME type ---");
  lines.push('<Files "apple-icon">');
  lines.push("  ForceType image/png");
  lines.push("</Files>");

  fs.writeFileSync(path.join(DEPLOY_DIR, ".htaccess"), lines.join("\n") + "\n");

  console.log(`Wrote deploy/.htaccess with ${redirects.length} redirect rules (primary domain: ${PRIMARY_DOMAIN}).`);
}

main();

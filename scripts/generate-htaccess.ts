import fs from "node:fs";
import path from "node:path";

const DEPLOY_DIR = path.join(__dirname, "..", "deploy");

// The site now lives on the new domain; the old domain stays registered
// purely to 301 every legacy URL (and any of its own old PHP paths) over to
// the equivalent page here, so old bookmarks/backlinks/indexed pages aren't
// lost. See: domain migration decision, Sept 2026.
const NEW_DOMAIN = "albanynyairporttaxi.com"; // apex, non-www
const OLD_DOMAIN = "albanyairport.taxi"; // apex, non-www — legacy domain, redirect-only

type Redirect = { from: string; to: string };

function parseLegacyUrl(from: string): { script: string; query: string } {
  const [script, query = ""] = from.replace(/^\//, "").split("?");
  return { script, query };
}

function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function main() {
  const redirects = JSON.parse(
    fs.readFileSync(path.join(DEPLOY_DIR, "redirects.json"), "utf8")
  ) as Redirect[];

  // --- deploy/.htaccess: goes in the NEW domain's docroot alongside the
  // static export. This domain never had the old PHP paths, so it only
  // needs to enforce its own canonical host/https. ---
  const siteLines: string[] = [];
  siteLines.push("# Generated by scripts/generate-htaccess.ts — do not hand-edit.");
  siteLines.push("# Regenerate via: npm run parse-dump && npm run generate-redirects && npm run generate-htaccess");
  siteLines.push("");
  siteLines.push("RewriteEngine On");
  siteLines.push("");
  siteLines.push("# --- Canonical host: force apex, non-www, https ---");
  siteLines.push(`RewriteCond %{HTTP_HOST} ^www\\.${NEW_DOMAIN.replace(/\./g, "\\.")}$ [NC]`);
  siteLines.push(`RewriteRule ^(.*)$ https://${NEW_DOMAIN}/$1 [R=301,L]`);
  siteLines.push("RewriteCond %{HTTPS} off");
  siteLines.push(`RewriteRule ^(.*)$ https://${NEW_DOMAIN}/$1 [R=301,L]`);
  siteLines.push("");
  siteLines.push("# --- Next.js dynamic icon/OG routes export as extensionless files; ---");
  siteLines.push("# --- force their real MIME type so browsers/social crawlers read them right ---");
  siteLines.push('<Files "icon">');
  siteLines.push("  ForceType image/png");
  siteLines.push("</Files>");
  siteLines.push('<Files "apple-icon">');
  siteLines.push("  ForceType image/png");
  siteLines.push("</Files>");
  siteLines.push('<Files "opengraph-image">');
  siteLines.push("  ForceType image/png");
  siteLines.push("</Files>");
  siteLines.push("");
  fs.writeFileSync(path.join(DEPLOY_DIR, ".htaccess"), siteLines.join("\n") + "\n");

  // --- deploy/old-domain.htaccess: goes in the OLD domain's docroot,
  // replacing the legacy PHP site entirely with redirect rules to the new
  // domain (absolute URLs), plus a catch-all for anything not in the old
  // sitemap. ---
  const legacyLines: string[] = [];
  legacyLines.push("# Generated by scripts/generate-htaccess.ts — do not hand-edit.");
  legacyLines.push("# Deploy this file as the ONLY thing in the OLD domain's docroot");
  legacyLines.push(`# (${OLD_DOMAIN}) — it exists solely to 301 legacy traffic to ${NEW_DOMAIN}.`);
  legacyLines.push("");
  legacyLines.push("RewriteEngine On");
  legacyLines.push("");
  legacyLines.push("# --- Legacy URL redirects (generated from the old PHP site's sitemap) ---");

  for (const redirect of redirects) {
    const { script, query } = parseLegacyUrl(redirect.from);
    const target = `https://${NEW_DOMAIN}${redirect.to}`;
    if (!query) {
      legacyLines.push(`RewriteRule ^${escapeRegex(script)}$ ${target}? [R=301,L]`);
      continue;
    }
    const escapedQuery = escapeRegex(query);
    legacyLines.push(`RewriteCond %{QUERY_STRING} ^${escapedQuery}$`);
    legacyLines.push(`RewriteRule ^${escapeRegex(script)}$ ${target}? [R=301,L]`);
  }

  legacyLines.push("");
  legacyLines.push("# --- Catch-all: anything else on the old domain goes to the new home page ---");
  legacyLines.push(`RewriteRule ^(.*)$ https://${NEW_DOMAIN}/ [R=301,L]`);

  fs.writeFileSync(path.join(DEPLOY_DIR, "old-domain.htaccess"), legacyLines.join("\n") + "\n");

  console.log(`Wrote deploy/.htaccess (new-domain canonical rules).`);
  console.log(`Wrote deploy/old-domain.htaccess with ${redirects.length} redirect rules + catch-all.`);
}

main();

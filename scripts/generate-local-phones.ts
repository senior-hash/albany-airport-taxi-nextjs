// One-off generator: produces lib/local-phones.ts, a slug -> local phone
// lookup used by the client-side Header to swap the canonical number for a
// county's real tracking number on that county's (and its cities') pages.
// Deliberately a client-side swap rather than baking local numbers into the
// server-rendered Header markup, since the Header is identical sitewide
// chrome — crawlers and JS-disabled visitors should keep seeing one
// canonical number there for NAP consistency, matching the Organization
// JSON-LD. (Page body content, like BookingCard, is different: it's
// genuinely specific to that one county/city, so rendering its real number
// server-side there is fine and already how it works.)
//
// Run with `npm run generate-local-phones` whenever county-tracking-phones.json
// or the county/city list changes. Not part of the regular build — its
// output is a committed, static data file.
import { writeFileSync, readFileSync } from "fs";
import { join } from "path";

type County = { id: number; slug: string; trackingPhone: string | null };
type City = { id: number; slug: string; countyId: number };

const CONTENT_DIR = join(__dirname, "..", "content");

function loadJson<T>(filename: string): T {
  return JSON.parse(readFileSync(join(CONTENT_DIR, filename), "utf8")) as T;
}

function main() {
  const counties = loadJson<County[]>("counties.json");
  const cities = loadJson<City[]>("cities.json");
  const countyById = new Map(counties.map((c) => [c.id, c]));

  const phoneBySlug: Record<string, string> = {};
  for (const county of counties) {
    if (county.trackingPhone) phoneBySlug[county.slug] = county.trackingPhone;
  }
  for (const city of cities) {
    const county = countyById.get(city.countyId);
    if (county?.trackingPhone) phoneBySlug[city.slug] = county.trackingPhone;
  }

  const out = `// Generated by scripts/generate-local-phones.ts — do not edit by hand.
// slug (county or city) -> that county's real local tracking phone number.
export const LOCAL_PHONE_BY_SLUG: Record<string, string> = ${JSON.stringify(phoneBySlug, null, 2)};
`;
  writeFileSync(join(__dirname, "..", "lib", "local-phones.ts"), out);
  console.log(`Wrote lib/local-phones.ts with ${Object.keys(phoneBySlug).length} entries.`);
}

main();
